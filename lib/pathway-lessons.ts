export function buildPathwayLessons(program: string) {
  const key = Object.keys(pathwayLessonTopics).find(name => name.toLowerCase() === program.trim().toLowerCase());
  if (!key) return null;
  const topics = pathwayLessonTopics[key];
  return [
    { title: `${key} Foundations`, progress: 0, lessons: topics.slice(0, 10).map((topic, index) => makeLesson(key, topic, index)) },
    { title: `${key} Applied Practice`, progress: 0, lessons: topics.slice(10).map((topic, index) => makeLesson(key, topic, index + 10)) }
  ];
}

function makeLesson(pathway: string, topic: string, index: number) {
  const focus = topic.toLowerCase();
  const review = topic.includes("Review");
  const definition = review
    ? `Review the foundational competencies, safety expectations, and exam blueprint relevant to ${pathway}. Check the current official certification or licensing requirements.`
    : `${topic} is an essential area of study for learners preparing for ${pathway}. Understand the underlying principles, your authorized role, and the applicable clinical or professional standards.`;
  const material = `Learning objective ${index + 1} of 20: explain ${focus} in the context of ${pathway}. Identify the purpose of this competency, the steps or concepts that apply in supervised practice, and the safety, quality, and documentation checks. Study the relevant training materials and current professional standards for your program. Work through an example with an instructor or approved learning resource, then explain when to stop and ask for guidance. This introductory overview is not a substitute for supervised skills instruction or a credentialing body's official content outline.`;
  const answer = `Follow the approved ${focus} workflow and seek qualified guidance when unsure.`;
  const explanation = `Safe ${focus} practice requires appropriate training, correct procedures, and awareness of the limits of the ${pathway} role.`;
  return {
    title: topic, time: "15 min", difficulty: index < 10 ? "Beginner" : "Intermediate",
    image: "/medpath-hero.png", definition, material,
    tip: `Review the key steps and terminology for ${focus}, then explain them aloud.`,
    warning: `Do not perform unfamiliar ${focus} tasks beyond your training or authorized scope.`,
    takeaways: [
      `Explain the purpose of ${focus} in ${pathway}.`,
      `Identify the safety and quality checks related to ${focus}.`,
      `Know when to escalate questions about ${focus} to a supervisor or instructor.`
    ],
    quiz: {
      question: `Which approach best supports safe learning and practice in ${topic}?`,
      options: [answer, "Skip verification steps to finish faster.", "Perform unfamiliar tasks without supervision.", "Ignore documentation and safety requirements."],
      answer, explanation
    },
    flashcards: [
      [`What topic does lesson ${index + 1} cover?`, topic],
      [`What is the key safety priority for ${topic}?`, `Follow approved procedures within your training and role.`],
      [`When should you seek help with ${topic}?`, "Whenever the task is unfamiliar, unsafe, or outside your authorized scope."]
    ]
  };
}
